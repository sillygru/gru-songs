  /// Evaluates the neural network for a single word feature vector.
  static double forwardWord(List<double> x) {
    final h1Act = List<double>.filled(h1, 0.0);
    for (var j = 0; j < h1; j++) {
      var s = b1[j];
      final lim = math.min(x.length, inDim);
      for (var i = 0; i < lim; i++) {
        s += x[i] * w1[i][j];
      }
      h1Act[j] = s > 0 ? s : 0.1 * s;
    }

    final h2Act = List<double>.filled(h2, 0.0);
    for (var j = 0; j < h2; j++) {
      var s = b2[j];
      for (var i = 0; i < h1; i++) {
        s += h1Act[i] * w2[i][j];
      }
      h2Act[j] = s > 0 ? s : 0.1 * s;
    }

    var out = b3;
    for (var i = 0; i < h2; i++) {
      out += h2Act[i] * w3[i];
    }

    final skipLim = math.min(x.length, inDim);
    for (var i = 0; i < skipLim; i++) {
      out += x[i] * wSkip[i];
    }

    if (out > 20.0) return out;
    if (out < -20.0) return 1e-4;
    return math.log(1.0 + math.exp(out));
  }

  /// Evaluates phrase silence ratio [0, 0.50].
  static double forwardPauseRatio(List<double> pFeat) {
    final h = List<double>.filled(8, 0.0);
    for (var j = 0; j < 8; j++) {
      var s = bPause[j];
      final lim = math.min(pFeat.length, 5);
      for (var i = 0; i < lim; i++) {
        s += pFeat[i] * wPause[i][j];
      }
      h[j] = s > 0 ? s : 0.1 * s;
    }

    var out = bPauseOut;
    for (var i = 0; i < 8; i++) {
      out += h[i] * wPauseOut[i];
    }

    final clamped = out.clamp(-10.0, 10.0);
    final sig = 1.0 / (1.0 + math.exp(-clamped));
    return sig * 0.50;
  }

  /// Estimates word-by-word timing for a line using the trained neural model.
  static List<RichLyricWord> estimateLineWords(
    String text,
    Duration lineStart,
    Duration lineEnd, {
    double songCps = 13.5,
  }) {
    final tokens = RegExp(r'\S+')
        .allMatches(text)
        .map((m) => m.group(0) ?? '')
        .where((s) => s.isNotEmpty)
        .toList();
    if (tokens.isEmpty) return const [];
    if (tokens.length == 1) {
      return [RichLyricWord(start: lineStart, end: lineEnd, text: tokens[0])];
    }

    final lineDurUs = (lineEnd - lineStart).inMicroseconds;
    final lineDurS = math.max(0.1, lineDurUs / 1000000.0);
    final lineChars = tokens.fold<int>(0, (sum, t) => sum + t.length);
    final lineCps = lineChars / lineDurS;
    final n = tokens.length;

    final wordFeatures = <List<double>>[];
    final pausesRaw = <int>[];

    for (var idx = 0; idx < n; idx++) {
      final tok = tokens[idx];
      final clean = tok.toLowerCase().replaceAll(RegExp(r"[^a-z0-9']"), '');
      final rawLen = math.max(1, clean.length);
      final isFunc = _functionWords.contains(clean) ? 1.0 : 0.0;
      final syl = _estimateSyllables(tok) / 4.0;
      final cLen = clean.replaceAll(RegExp(r'[^a-z0-9]'), '').length / 10.0;
      final vowels = RegExp(r'[aeiouy]+').allMatches(clean).length;
      final vDensity = vowels / rawLen.toDouble();
      final diph = _estimateDiphthongs(tok) / 2.0;

      final isFinal = idx == n - 1 ? 1.0 : 0.0;
      final isPenult = idx == n - 2 ? 1.0 : 0.0;
      final isPickup = (idx == 0 && isFunc > 0.5 && n > 2) ? 1.0 : 0.0;
      final relPos = idx / math.max(1.0, (n - 1).toDouble());

      final hasComma = (tok.endsWith(',') ||
              tok.endsWith(';') ||
              tok.endsWith('-') ||
              tok.endsWith('~'))
          ? 1.0
          : 0.0;
      final hasStop =
          (tok.endsWith('.') || tok.endsWith('!') || tok.endsWith('?'))
              ? 1.0
              : 0.0;

      var plosiveCount = 0;
      var fricativeCount = 0;
      var sonorantCount = 0;
      for (var i = 0; i < clean.length; i++) {
        final ch = clean[i];
        if (_plosives.contains(ch)) plosiveCount++;
        if (_fricatives.contains(ch)) fricativeCount++;
        if (_sonorants.contains(ch)) sonorantCount++;
      }

      final prevTok = idx > 0 ? tokens[idx - 1] : '';
      final prevClean =
          prevTok.toLowerCase().replaceAll(RegExp(r"[^a-z0-9']"), '');
      final prevIsFunc = _functionWords.contains(prevClean) ? 1.0 : 0.0;

      final nextTok = idx < n - 1 ? tokens[idx + 1] : '';
      final nextClean =
          nextTok.toLowerCase().replaceAll(RegExp(r"[^a-z0-9']"), '');
      final nextIsFunc = _functionWords.contains(nextClean) ? 1.0 : 0.0;

      final featVec = <double>[
        syl,
        cLen,
        vDensity,
        diph,
        isFunc,
        isPickup,
        isPenult,
        isFinal,
        relPos,
        hasComma,
        hasStop,
        clean.length / math.max(1.0, lineChars.toDouble()),
        prevIsFunc,
        nextIsFunc,
        plosiveCount / rawLen.toDouble(),
        fricativeCount / rawLen.toDouble(),
        sonorantCount / rawLen.toDouble(),
        math.min(2.0, lineCps / 15.0),
        math.min(2.0, lineDurS / 5.0),
        math.min(2.0, songCps / 15.0),
        lineCps < 7.0 ? 1.0 : 0.0,
        lineCps > 14.0 ? 1.0 : 0.0,
        0.5,
        0.5,
        0.0,
        0.5,
        0.5,
        0.0,
        0.0,
        0.5,
      ];
      wordFeatures.add(featVec);

      var pType = 0;
      if (idx != n - 1) {
        if (hasComma > 0.5) {
          pType = 1;
        } else if (hasStop > 0.5) {
          pType = 2;
        }
      }
      pausesRaw.add(pType);
    }

    final expectedFromCharsUs = ((lineChars / songCps) * 1000000).round();
    final totalSyllablesCount =
        tokens.map(_estimateSyllables).fold<int>(0, (s, c) => s + c);
    final expectedFromSyllablesUs =
        ((totalSyllablesCount * 0.24) * 1000000).round();
    final baseDurationUs =
        ((expectedFromCharsUs * 0.65) + (expectedFromSyllablesUs * 0.35))
            .round();
    final minVocalUs = math.max<int>(tokens.length * 140000, lineChars * 32000);

    final isCjk =
        RegExp(r'[\u4e00-\u9fff\u3040-\u309f\u30a0-\u30ff\uac00-\ud7af]')
            .hasMatch(text);

    int vocalSpanUs;
    if (lineDurUs >= 7500000) {
      final maxCharDurationUs = songCps > 16.0 ? 120000 : 220000;
      final maxBreakCapUs = songCps > 16.0 ? 2500000 : 3400000;
      final sustainedCeilingUs = math.min<int>(
        maxBreakCapUs,
        math.max<int>(
          (baseDurationUs * 1.8).round(),
          lineChars * maxCharDurationUs,
        ),
      );
      vocalSpanUs = sustainedCeilingUs.clamp(minVocalUs, lineDurUs);
    } else {
      final breathUs = ((lineDurUs * 0.08).round()).clamp(150000, 400000);
      final availableSpanUs = math.max(minVocalUs, lineDurUs - breathUs);

      final isSustainedPhrase = n == 1 ||
          (songCps <= 12.5 && n <= 6) ||
          (songCps <= 14.5 && n <= 4 && lineDurUs <= 6800000);

      if (lineDurUs <= (baseDurationUs * 1.15).round()) {
        vocalSpanUs = availableSpanUs;
      } else if (isSustainedPhrase) {
        final maxPhraseCeilingUs = isCjk
            ? math.min(lineChars * 550000, availableSpanUs)
            : math.min(6500000, availableSpanUs);
        vocalSpanUs = maxPhraseCeilingUs.clamp(minVocalUs, availableSpanUs);
      } else {
        final maxElasticity = songCps > 16.0 ? 0.25 : 0.40;
        final elasticity = (1.0 - (n - 3) * 0.14).clamp(0.12, maxElasticity);
        final elasticUs =
            (baseDurationUs + (availableSpanUs - baseDurationUs) * elasticity)
                .round();
        vocalSpanUs = elasticUs.clamp(minVocalUs, availableSpanUs);
      }
    }

    final pausesUs = <int>[];
    for (final pt in pausesRaw) {
      if (pt == 1) {
        pausesUs.add(280000);
      } else if (pt == 2) {
        pausesUs.add(420000);
      } else {
        pausesUs.add(0);
      }
    }

    final wordWeights = <double>[];
    for (var i = 0; i < n; i++) {
      var w = forwardWord(wordFeatures[i]);
      if (i == 0 && wordFeatures[i][5] > 0.5) {
        // Pickup lead-in function word
        w *= 0.35;
      }
      wordWeights.add(w);
    }
    final totalWeight = wordWeights.fold<double>(0.0, (s, w) => s + w);
    final totalPauseUs = pausesUs.fold<int>(0, (s, p) => s + p);
    final allocatableUs = math.max(0, vocalSpanUs - totalPauseUs);

    final result = <RichLyricWord>[];
    var cursorUs = 0;
    for (var i = 0; i < n; i++) {
      final wordDurationUs = totalWeight > 0
          ? ((allocatableUs * wordWeights[i]) / totalWeight).round()
          : (allocatableUs / n).round();

      final wordStart = lineStart + Duration(microseconds: cursorUs);
      final wordEnd = wordStart + Duration(microseconds: wordDurationUs);
      cursorUs += wordDurationUs + pausesUs[i];

      result.add(RichLyricWord(
        start: wordStart,
        end: wordEnd,
        text: tokens[i],
      ));
    }
    return result;
  }

  static int _estimateSyllables(String word) {
    var syllables = 0;
    final latinBuffer = StringBuffer();

    for (final rune in word.runes) {
      if ((rune >= 0x4E00 && rune <= 0x9FFF) ||
          (rune >= 0x3040 && rune <= 0x309F) ||
          (rune >= 0x30A0 && rune <= 0x30FF) ||
          (rune >= 0xAC00 && rune <= 0xD7AF)) {
        syllables++;
      } else {
        latinBuffer.writeCharCode(rune);
      }
    }

    final latin =
        latinBuffer.toString().toLowerCase().replaceAll(RegExp(r"[^a-z']"), '');
    if (latin.isNotEmpty) {
      var count = 0;
      var inVowels = false;
      const vowels = {'a', 'e', 'i', 'o', 'u', 'y'};

      for (var i = 0; i < latin.length; i++) {
        final isVowel = vowels.contains(latin[i]);
        if (isVowel && !inVowels) {
          count++;
          inVowels = true;
        } else if (!isVowel) {
          inVowels = false;
        }
      }

      if (count > 1 && latin.endsWith('e') && !latin.endsWith('le')) {
        count--;
      }
      syllables += math.max(1, count);
    }
    return math.max(1, syllables);
  }

  static int _estimateDiphthongs(String word) {
    final clean = word.toLowerCase().replaceAll(RegExp(r"[^a-z']"), '');
    var count = 0;
    for (final d in _diphthongs) {
      if (clean.contains(d)) count++;
    }
    return count;
  }
