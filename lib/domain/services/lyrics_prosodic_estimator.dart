    final vocalSpanUs = math.max(100000, lineDurUs - silenceUs);
    final allocatableUs = math.max(0, vocalSpanUs - totalPauseUs);

    final wordWeights = <double>[];
    for (var i = 0; i < n; i++) {
      var w = forwardWord(wordFeatures[i]);
      if (i == 0 && wordFeatures[i][5] > 0.5) {
        w *= 0.35; // exact python pickup damping
      }
      wordWeights.add(w);
    }

    var totalWeight = wordWeights.fold<double>(0.0, (s, w) => s + w);
    if (totalWeight <= 0) {
      totalWeight = n.toDouble();
      for (var i = 0; i < n; i++) {
        wordWeights[i] = 1.0;
      }
    }

    final cumWeights = <double>[0.0];
    for (final w in wordWeights) {
      cumWeights.add(cumWeights.last + w);
    }

    // Deterministic word boundary placement (mirrors aligner.py:42-50)
    final rawBoundaries = <int>[lineStart.inMicroseconds];
    for (var i = 1; i < n; i++) {
      final split = lineStart.inMicroseconds + (allocatableUs * (cumWeights[i] / totalWeight)).round() + pausesUs.sublist(0, i).fold<int>(0, (s, p) => s + p);
      rawBoundaries.add(split);
    }
    rawBoundaries.add(lineStart.inMicroseconds + vocalSpanUs);

    for (var i = 1; i < rawBoundaries.length; i++) {
      if (rawBoundaries[i] <= rawBoundaries[i - 1] + 20000) {
        rawBoundaries[i] = rawBoundaries[i - 1] + 20000;
      }
    }

    final result = <RichLyricWord>[];
    for (var i = 0; i < n; i++) {
      result.add(RichLyricWord(
        start: Duration(microseconds: rawBoundaries[i]),
        end: Duration(microseconds: rawBoundaries[i + 1]),
        text: tokens[i],
      ));
    }
    return result;
  }

  static int _estimateSyllables(String word) {
    var syllables = 0;
    final latinBuffer = StringBuffer();

    for (final rune in word.runes) {
      if ((rune >= 0x4E00 && rune <= 0x9FFF) || (rune >= 0x3040 && rune <= 0x309F) || (rune >= 0x30A0 && rune <= 0x30FF) || (rune >= 0xAC00 && rune <= 0xD7AF)) {
        syllables++;
      } else {
        latinBuffer.writeCharCode(rune);
      }
    }

    final latin = latinBuffer.toString().toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
    if (latin.isNotEmpty) {
      var count = 0;
      var inVowels = false;
      const vowels = {'a', 'e', 'i', 'o', 'u', 'y'};

      for (var i = 0; i < latin.length; i++) {
        final isVowel = vowels.contains(latin[i]);
        if (isVowel && !inVowels) {
          count++;
          inVowels = true;
        } else if (!isVowel) {
          inVowels = false;
        }
      }

      if (count > 1 && latin.endsWith('e') && !latin.endsWith('le')) {
        count--;
      }
      syllables += math.max(1, count);
    }
    return math.max(1, syllables);
  }

  static int _estimateDiphthongs(String word) {
    final clean = word.toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
    var count = 0;
    for (final d in _diphthongs) {
      if (clean.contains(d)) count++;
    }
    return count;
  }
