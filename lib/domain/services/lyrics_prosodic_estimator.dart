      } else if (pt == 2) {
        pausesUs.add(stopPauseUs);
      } else {
        pausesUs.add(0);
      }
    }

    final wordWeights = <double>[];
    for (var i = 0; i < n; i++) {
      var w = forwardWord(wordFeatures[i]);
      if (i == 0 && wordFeatures[i][5] > 0.5) {
        w *= 0.22;
      }
      wordWeights.add(w);
    }

    final totalWeight = wordWeights.fold<double>(0.0, (s, w) => s + w);
    final totalPauseUs = pausesUs.fold<int>(0, (s, p) => s + p);
    final allocatableUs = math.max(0, vocalSpanUs - totalPauseUs);

    final result = <RichLyricWord>[];
    var cursorUs = 0;
    for (var i = 0; i < n; i++) {
      final wordDurationUs = totalWeight > 0 ? ((allocatableUs * wordWeights[i]) / totalWeight).round() : (allocatableUs / n).round();

      final wordStart = lineStart + Duration(microseconds: cursorUs);
      final wordEnd = wordStart + Duration(microseconds: wordDurationUs);
      cursorUs += wordDurationUs + pausesUs[i];

      result.add(RichLyricWord(
        start: wordStart,
        end: wordEnd,
        text: tokens[i],
      ));
    }
    return result;
  }

  static int _estimateSyllables(String word) {
    var syllables = 0;
    final latinBuffer = StringBuffer();

    for (final rune in word.runes) {
      if ((rune >= 0x4E00 && rune <= 0x9FFF) || (rune >= 0x3040 && rune <= 0x309F) || (rune >= 0x30A0 && rune <= 0x30FF) || (rune >= 0xAC00 && rune <= 0xD7AF)) {
        syllables++;
      } else {
        latinBuffer.writeCharCode(rune);
      }
    }

    final latin = latinBuffer.toString().toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
    if (latin.isNotEmpty) {
      var count = 0;
      var inVowels = false;
      const vowels = {'a', 'e', 'i', 'o', 'u', 'y'};

      for (var i = 0; i < latin.length; i++) {
        final isVowel = vowels.contains(latin[i]);
        if (isVowel && !inVowels) {
          count++;
          inVowels = true;
        } else if (!isVowel) {
          inVowels = false;
        }
      }

      if (count > 1 && latin.endsWith('e') && !latin.endsWith('le')) {
        count--;
      }
      syllables += math.max(1, count);
    }
    return math.max(1, syllables);
  }

  static int _estimateDiphthongs(String word) {
    final clean = word.toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
    var count = 0;
    for (final d in _diphthongs) {
      if (clean.contains(d)) count++;
    }
    return count;
  }
