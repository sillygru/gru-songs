  /// Computes the forward pass of the Res-MLP on a 30-D word feature vector.
  static double forwardWord(List<double> x) {
    final hidden1 = List<double>.filled(h1, 0.0);
    for (var j = 0; j < h1; j++) {
      var sum = b1[j];
      final limit = math.min(x.length, inDim);
      for (var i = 0; i < limit; i++) {
        sum += x[i] * w1[i][j];
      }
      hidden1[j] = sum > 0 ? sum : 0.1 * sum;
    }

    final hidden2 = List<double>.filled(h2, 0.0);
    for (var j = 0; j < h2; j++) {
      var sum = b2[j];
      for (var i = 0; i < h1; i++) {
        sum += hidden1[i] * w2[i][j];
      }
      hidden2[j] = sum > 0 ? sum : 0.1 * sum;
    }

    var out = b3;
    for (var i = 0; i < h2; i++) {
      out += hidden2[i] * w3[i];
    }

    final limit = math.min(x.length, inDim);
    for (var i = 0; i < limit; i++) {
      out += x[i] * wSkip[i];
    }

    if (out > 20) return out;
    if (out < -20) return 1e-4;
    return math.log(1.0 + math.exp(out));
  }

  /// Computes the phrase silence ratio (0.0 to 0.50) from line cadence features.
  static double forwardPauseRatio(List<double> pFeat) {
    final h = List<double>.filled(8, 0.0);
    for (var j = 0; j < 8; j++) {
      var sum = bPause[j];
      final limit = math.min(pFeat.length, 5);
      for (var i = 0; i < limit; i++) {
        sum += pFeat[i] * wPause[i][j];
      }
      h[j] = sum > 0 ? sum : 0.1 * sum;
    }
    var out = bPauseOut;
    for (var i = 0; i < 8; i++) {
      out += h[i] * wPauseOut[i];
    }
    final sig = 1.0 / (1.0 + math.exp(-out.clamp(-10.0, 10.0)));
    return sig * 0.50;
  }

  /// Estimates sub-second start and end boundaries for words within a lyric line.
  static List<RichLyricWord> estimateLineWords(
    String text,
    Duration lineStart,
    Duration lineEnd, {
    double songCps = 13.5,
  }) {
    final tokens = text.split(RegExp(r'\s+')).where((t) => t.isNotEmpty).toList();
    final n = tokens.length;
    if (n == 0) return const [];
    if (n == 1) {
      return [
        RichLyricWord(
          start: lineStart,
          end: lineEnd,
          text: tokens.first,
        ),
      ];
    }

    final lineDurUs = lineEnd.inMicroseconds - lineStart.inMicroseconds;
    final lineDurS = math.max(0.1, lineDurUs / 1000000.0);
    final lineChars = tokens.fold<int>(0, (s, t) => s + t.length);
    final lineCps = lineChars / lineDurS;

    final wordFeatures = <List<double>>[];
    final pausesRaw = <int>[];

    for (var idx = 0; idx < n; idx++) {
      final tok = tokens[idx];
      final clean = tok.toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
      final rawLen = math.max(1, clean.length);
      final isFunc = _functionWords.contains(clean) ? 1.0 : 0.0;
      final syl = _estimateSyllables(tok) / 4.0;
      final cLen = clean.replaceAll(RegExp(r'[^\w]'), '').length / 10.0;
      final vowels = RegExp(r'[aeiouy]+').allMatches(clean).length;
      final vDensity = vowels / rawLen.toDouble();
      final diph = _estimateDiphthongs(tok) / 2.0;

      final isFinal = idx == n - 1 ? 1.0 : 0.0;
      final isPenult = idx == n - 2 ? 1.0 : 0.0;
      final isPickup = (idx == 0 && isFunc > 0.5 && n > 2) ? 1.0 : 0.0;
      final relPos = idx / math.max(1.0, (n - 1).toDouble());

      final hasComma = (tok.endsWith(',') || tok.endsWith(';') || tok.endsWith('-') || tok.endsWith('~')) ? 1.0 : 0.0;
      final hasStop = (tok.endsWith('.') || tok.endsWith('!') || tok.endsWith('?')) ? 1.0 : 0.0;

      var plosives = 0;
      var fricatives = 0;
      var sonorants = 0;
      for (var c = 0; c < clean.length; c++) {
        final ch = clean[c];
        if (_plosives.contains(ch)) plosives++;
        if (_fricatives.contains(ch)) fricatives++;
        if (_sonorants.contains(ch)) sonorants++;
      }

      final prevTok = idx > 0 ? tokens[idx - 1] : '';
      final prevClean = prevTok.toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
      final prevIsFunc = _functionWords.contains(prevClean) ? 1.0 : 0.0;

      final nextTok = idx < n - 1 ? tokens[idx + 1] : '';
      final nextClean = nextTok.toLowerCase().replaceAll(RegExp(r"[^\w']"), '');
      final nextIsFunc = _functionWords.contains(nextClean) ? 1.0 : 0.0;

      final featVec = <double>[
        syl,
        cLen,
        vDensity,
        diph,
        isFunc,
        isPickup,
        isPenult,
        isFinal,
        relPos,
        hasComma,
        hasStop,
        clean.length / math.max(1.0, lineChars.toDouble()),
        prevIsFunc,
        nextIsFunc,
        plosives / rawLen.toDouble(),
        fricatives / rawLen.toDouble(),
        sonorants / rawLen.toDouble(),
        math.min(2.0, lineCps / 15.0),
        math.min(2.0, lineDurS / 5.0),
        math.min(2.0, songCps / 15.0),
        lineCps < 7.0 ? 1.0 : 0.0,
        lineCps > 14.0 ? 1.0 : 0.0,
        0.5,
        0.5,
        0.0,
        0.5,
        0.5,
        0.0,
        0.0,
        0.0,
      ];
      wordFeatures.add(featVec);

      var pType = 0;
      if (isFinal < 0.5) {
        if (hasComma > 0.5) {
          pType = 1;
        } else if (hasStop > 0.5) {
          pType = 2;
        }
      }
      pausesRaw.add(pType);
    }

    final baseDurationUs = ((lineChars / math.max(6.0, songCps)) * 1000000.0).round();
    final minVocalUs = math.max<int>(tokens.length * 140000, lineChars * 32000);

    final isCjk = RegExp(r'[一-鿿぀-ゟ゠-ヿ가-힯]').hasMatch(text);

    int vocalSpanUs;
    if (lineDurUs >= 7500000) {
      final maxCharDurationUs = songCps > 16.0 ? 120000 : 220000;
      final maxBreakCapUs = songCps > 16.0 ? 2500000 : 3400000;
      final sustainedCeilingUs = math.min<int>(
        maxBreakCapUs,
        math.max<int>(
          (baseDurationUs * 1.8).round(),
          lineChars * maxCharDurationUs,
        ),
      );
      vocalSpanUs = sustainedCeilingUs.clamp(minVocalUs, lineDurUs);
    } else {
      final breathUs = ((lineDurUs * 0.08).round()).clamp(150000, 400000);
      final availableSpanUs = math.max(minVocalUs, lineDurUs - breathUs);

      final isSustainedPhrase = n == 1 || (songCps <= 12.5 && n <= 6) || (songCps <= 14.5 && n <= 4 && lineDurUs <= 6800000);

      if (lineDurUs <= (baseDurationUs * 1.15).round()) {
        vocalSpanUs = availableSpanUs;
      } else if (isSustainedPhrase) {
        final maxPhraseCeilingUs = isCjk ? math.min(lineChars * 550000, availableSpanUs) : math.min(6500000, availableSpanUs);
        vocalSpanUs = maxPhraseCeilingUs.clamp(minVocalUs, availableSpanUs);
      } else {
        final maxElasticity = songCps > 16.0 ? 0.25 : 0.40;
        final elasticity = (1.0 - (n - 3) * 0.14).clamp(0.12, maxElasticity);
        final elasticUs = (baseDurationUs + (availableSpanUs - baseDurationUs) * elasticity).round();
        vocalSpanUs = elasticUs.clamp(minVocalUs, availableSpanUs);
      }
    }

    final commaPauseUs = songCps > 14.0 ? 180000 : (songCps < 9.0 ? 340000 : 280000);
    final stopPauseUs = songCps > 14.0 ? 280000 : (songCps < 9.0 ? 520000 : 420000);

    final pausesUs = <int>[];
    for (final pt in pausesRaw) {
